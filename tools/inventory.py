#!/usr/bin/env python3
"""Inventory of the extracted PSP ISO tree (stdlib only).

Writes assets/hm-raw/inventory.json (git-ignored) and docs/inventory.md
(sizes, magics, entropy; no content).
"""
import hashlib
import json
import math
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RAW = os.path.join(REPO, "assets", "hm-raw")
ROOT = os.path.join(RAW, "extracted")
CHUNK = 1 << 20

MAGICS = [
    (b"~PSP", "~PSP (encrypted PSP module)"),
    (b"\x7fELF", "ELF/PRX (plain)"),
    (b"RIFF", "RIFF"),
    (b"VAGp", "VAGp"),
    (b"pBAV", "pBAV (VAGp, byte-swapped)"),
    (b"\x89PNG", "PNG"),
    (b"\x00PBP", "PBP"),
    (b"\x00PSF", "SFO"),
]


def magic_name(head):
    for m, n in MAGICS:
        if head.startswith(m):
            return n
    return "unknown"


def scan(path):
    """Return size, sha1, entropy (Shannon, bits/byte), head bytes in one pass."""
    sha = hashlib.sha1()
    counts = [0] * 256
    head = b""
    size = 0
    with open(path, "rb") as f:
        while True:
            b = f.read(CHUNK)
            if not b:
                break
            if not head:
                head = b[:16]
            sha.update(b)
            size += len(b)
            for i, c in enumerate(_hist(b)):
                counts[i] += c
    ent = 0.0
    if size:
        for c in counts:
            if c:
                p = c / size
                ent -= p * math.log2(p)
    return size, sha.hexdigest(), ent, head


def _hist(b):
    # bytes.count per value is fast enough in C; avoids a Python-level loop per byte
    return [b.count(bytes([i])) for i in range(256)]


def main():
    entries = []
    for dp, _, fns in sorted(os.walk(ROOT)):
        for fn in sorted(fns):
            p = os.path.join(dp, fn)
            size, sha1, ent, head = scan(p)
            entries.append({
                "path": os.path.relpath(p, ROOT),
                "ext": os.path.splitext(fn)[1].lower(),
                "size": size,
                "sha1": sha1,
                "entropy": round(ent, 3),
                "magic_hex": head[:8].hex(),
                "magic": magic_name(head),
            })
            print(entries[-1]["path"], size, file=sys.stderr)
    with open(os.path.join(RAW, "inventory.json"), "w") as f:
        json.dump(entries, f, indent=1)
    lines = ["# Inventory of the extracted ISO tree", "",
             "Generated by `tools/inventory.py`. Names and statistics only; no content.",
             "Entropy is Shannon bits per byte (8.0 = encrypted or well compressed).", "",
             "| Path | Size (bytes) | First 8 bytes | Magic | Entropy | SHA-1 |",
             "|---|---:|---|---|---:|---|"]
    for e in entries:
        lines.append("| `%s` | %d | `%s` | %s | %.3f | `%s` |" % (
            e["path"], e["size"], e["magic_hex"], e["magic"], e["entropy"], e["sha1"][:12]))
    lines += ["", "Total: %d files, %d bytes." % (len(entries), sum(e["size"] for e in entries)), ""]
    with open(os.path.join(REPO, "docs", "inventory.md"), "w") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
