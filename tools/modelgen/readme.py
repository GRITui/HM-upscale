import os

from .models import EXAMPLE_SCENE

TEMPLATE = """# HM Phase 6 placeholder models

Generated by `python3 -m tools.modelgen` (run from the repo root). Do not edit by hand:
the generator is deterministic, so re-running produces byte-identical files.

All geometry is original and procedural (boxes, frusta, low-poly spheres). Nothing is read from
`assets/` or the extracted game data. glTF 2.0, +Y up, metres, 1 tile = 1 m, origin at ground level
centre. Flat shaded (per-face normals). Colour is in `COLOR_0` (linear, normalised ubyte) on one
shared material `hm_vertex_color`; there is no texture. In Unity use a vertex-colour shader
(glTFast `glTF/PbrMetallicRoughness` honours COLOR_0, or a Shader Graph with the Vertex Color node).

Characters are static but split into named child nodes (`body`, `head`, `arm_l`, `arm_r`, `leg_l`,
`leg_r`) with pivots at the joints, so they can be animated by rotating child transforms.

Budget: whole scene under ~50k tris. Counts below are per model.

| Model | Tris | Bytes | Parts |
|---|---:|---:|---|
{rows}
| **Total (one of each)** | **{total}** | | |

Example full-scene budget ({scene_total} tris): {scene}.
The unit test asserts this stays under 50,000.

Test: `python3 -m unittest tools.modelgen.test_modelgen -v`
"""


def write_readme(out, rows):
    lines = ["| %s | %d | %d | %s |" % (n, t, b, ", ".join(p)) for n, t, b, p in rows]
    with open(os.path.join(out, "README.md"), "w") as f:
        f.write(TEMPLATE.format(rows="\n".join(lines), total=sum(r[1] for r in rows),
                                  scene_total=sum(t * EXAMPLE_SCENE.get(n, 0) for n, t, _, _ in rows),
                                  scene=", ".join("%d x %s" % (c, n) for n, c in EXAMPLE_SCENE.items())))
